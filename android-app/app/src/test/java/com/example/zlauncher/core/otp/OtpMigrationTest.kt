package com.example.zlauncher.core.otp

import org.junit.Assert.assertEquals
import org.junit.Assert.assertTrue
import org.junit.Test

/**
 * Google Authenticator の書き出し形式の読み取り。
 *
 * **この形式は公開仕様ではない。** ここで固定しているのは、広く知られているスキーマどおりに
 * 組み立てた**合成データ**であって、本物の書き出しではない。パーサーの取り違え（フィールド
 * 番号の入れ替わり等）はこれで防げるが、スキーマ自体が違っていた場合は防げない —
 * だから取り込み画面は、保存前に読み取った中身を必ず一覧で見せる。
 */
class OtpMigrationTest {

    /** 上の注記のとおり、tools 側で組み立てた 3 件（TOTP 2 件 + HOTP 1 件） */
    private val payload = byteArrayOf(
        0x0a, 0x39, 0x0a, 0x14, 0x31, 0x32, 0x33, 0x34, 0x35, 0x36, 0x37, 0x38, 0x39, 0x30,
        0x31, 0x32, 0x33, 0x34, 0x35, 0x36, 0x37, 0x38, 0x39, 0x30, 0x12, 0x13, 0x6f, 0x63,
        0x74, 0x6f, 0x63, 0x61, 0x74, 0x40, 0x65, 0x78, 0x61, 0x6d, 0x70, 0x6c, 0x65, 0x2e,
        0x63, 0x6f, 0x6d, 0x1a, 0x06, 0x47, 0x69, 0x74, 0x48, 0x75, 0x62, 0x20, 0x01, 0x28,
        0x01, 0x30, 0x02, 0x0a, 0x33, 0x0a, 0x20, 0x31, 0x32, 0x33, 0x34, 0x35, 0x36, 0x37,
        0x38, 0x39, 0x30, 0x31, 0x32, 0x33, 0x34, 0x35, 0x36, 0x37, 0x38, 0x39, 0x30, 0x31,
        0x32, 0x33, 0x34, 0x35, 0x36, 0x37, 0x38, 0x39, 0x30, 0x31, 0x32, 0x12, 0x04, 0x72,
        0x6f, 0x6f, 0x74, 0x1a, 0x03, 0x41, 0x57, 0x53, 0x20, 0x02, 0x28, 0x02, 0x30, 0x02,
        0x0a, 0x35, 0x0a, 0x10, 0x73, 0x65, 0x63, 0x72, 0x65, 0x74, 0x73, 0x65, 0x63, 0x72,
        0x65, 0x74, 0x73, 0x65, 0x63, 0x72, 0x12, 0x13, 0x63, 0x6f, 0x75, 0x6e, 0x74, 0x65,
        0x72, 0x40, 0x65, 0x78, 0x61, 0x6d, 0x70, 0x6c, 0x65, 0x2e, 0x63, 0x6f, 0x6d, 0x1a,
        0x06, 0x4c, 0x65, 0x67, 0x61, 0x63, 0x79, 0x20, 0x01, 0x28, 0x01, 0x30, 0x01, 0x10,
        0x01, 0x18, 0x01, 0x20, 0x00, 0x28, 0x87.toByte(), 0xad.toByte(), 0x4b,
    )

    @Test
    fun `entries come back with issuer account algorithm and digits`() {
        val drafts = OtpMigration.decodePayload(payload)

        assertEquals(2, drafts.size)

        assertEquals("GitHub", drafts[0].issuer)
        assertEquals("octocat@example.com", drafts[0].account)
        assertEquals(OtpAlgorithm.SHA1, drafts[0].algorithm)
        assertEquals(6, drafts[0].digits)
        assertEquals("12345678901234567890".toByteArray().toList(), drafts[0].secret.toList())

        assertEquals("AWS", drafts[1].issuer)
        assertEquals("root", drafts[1].account)
        assertEquals(OtpAlgorithm.SHA256, drafts[1].algorithm)
        assertEquals(8, drafts[1].digits)
    }

    /** カウンタ式は落とす。取り込んでもずれた時点で直せない */
    @Test
    fun `hotp entries are dropped`() {
        assertTrue(OtpMigration.decodePayload(payload).none { it.issuer == "Legacy" })
    }

    /** 書き出しに周期は入らない。Google Authenticator は 30 秒固定 */
    @Test
    fun `period falls back to thirty seconds`() {
        assertTrue(OtpMigration.decodePayload(payload).all { it.periodSeconds == 30 })
    }

    /** 途中で切れたデータでも落とさず、読めたぶんだけ返す */
    @Test
    fun `a truncated payload yields nothing instead of crashing`() {
        assertEquals(emptyList<OtpDraft>(), OtpMigration.decodePayload(payload.copyOfRange(0, 7)))
    }

    @Test
    fun `an empty payload is not an error`() {
        assertEquals(emptyList<OtpDraft>(), OtpMigration.decodePayload(ByteArray(0)))
    }
}
